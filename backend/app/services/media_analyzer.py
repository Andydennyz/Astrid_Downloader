from __future__ import annotations

import re
from datetime import datetime, timezone
import mimetypes
from typing import Any
from urllib.parse import urlsplit

import yt_dlp


class MediaAnalysisError(Exception):
    pass


_PLATFORM_DOMAINS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("youtube", ("youtube.com", "youtu.be")),
    ("vimeo", ("vimeo.com",)),
    ("soundcloud", ("soundcloud.com",)),
    ("twitch", ("twitch.tv",)),
    ("bandcamp", ("bandcamp.com",)),
    ("facebook", ("facebook.com", "fb.watch")),
    ("instagram", ("instagram.com", "instagr.am")),
    ("pinterest", ("pinterest.com", "pin.it")),
    ("tiktok", ("tiktok.com",)),
    ("x", ("twitter.com", "x.com")),
    ("reddit", ("reddit.com", "redd.it")),
    ("dailymotion", ("dailymotion.com", "dai.ly")),
)


def detect_platform(url: str) -> str:
    try:
        hostname = (urlsplit(url).hostname or "").rstrip(".").lower()
    except ValueError:
        return "other"

    for platform, domains in _PLATFORM_DOMAINS:
        if any(
            hostname == domain or hostname.endswith(f".{domain}")
            for domain in domains
        ):
            return platform
    return "other"


def _format_formats(info: dict[str, Any]) -> list[dict[str, Any]]:
    formats: list[dict[str, Any]] = []
    for entry in info.get("formats", []) or []:
        if not entry.get("format_id"):
            continue

        estimated_size = entry.get("filesize")
        if not isinstance(estimated_size, (int, float)) or estimated_size <= 0:
            estimated_size = entry.get("filesize_approx")
        if (
            not isinstance(estimated_size, (int, float))
            or isinstance(estimated_size, bool)
            or estimated_size <= 0
        ):
            estimated_size = None
        elif isinstance(estimated_size, float):
            estimated_size = int(estimated_size)

        height = entry.get("height")
        width = entry.get("width")
        if isinstance(height, int) and isinstance(width, int):
            height = min(height, width)

        format_kind = "muxed" if entry.get("vcodec") not in (None, "none") and entry.get("acodec") not in (None, "none") else "video" if entry.get("vcodec") not in (None, "none") else "audio"
        format_record = {
            "formatId": str(entry.get("format_id", "unknown")),
            "kind": format_kind,
            "container": (entry.get("ext") or "mp4").lower(),
            "height": height,
            "fps": entry.get("fps"),
            "videoCodec": entry.get("vcodec"),
            "audioCodec": entry.get("acodec"),
            "bitrateKbps": int(entry.get("tbr") or 0) if entry.get("tbr") is not None else None,
            "sampleRateHz": entry.get("asr"),
            "estimatedSizeBytes": estimated_size,
            "note": entry.get("format_note"),
        }
        formats.append(format_record)

    if not formats:
        formats.append(
            {
                "formatId": "best",
                "kind": "muxed",
                "container": "mp4",
                "height": 1080,
                "note": "Fallback heuristic format generated by the backend.",
            }
        )

    return formats


def _format_uploaded_at(info: dict[str, Any]) -> str:
    timestamp = info.get("timestamp")
    if isinstance(timestamp, (int, float)) and not isinstance(timestamp, bool):
        try:
            return datetime.fromtimestamp(timestamp, timezone.utc).isoformat()
        except (OSError, OverflowError, ValueError):
            pass
    elif isinstance(timestamp, str) and timestamp.strip():
        value = timestamp.strip()
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return parsed.astimezone(timezone.utc).isoformat()
        except ValueError:
            try:
                return datetime.fromtimestamp(float(value), timezone.utc).isoformat()
            except (OSError, OverflowError, ValueError):
                pass

    upload_date = info.get("upload_date")
    if isinstance(upload_date, str):
        try:
            return datetime.strptime(upload_date, "%Y%m%d").replace(tzinfo=timezone.utc).isoformat()
        except ValueError:
            pass

    return datetime.now(timezone.utc).isoformat()


def analyze_media_url(url: str) -> dict[str, Any]:
    platform = detect_platform(url)
    if not url:
        raise ValueError("A media URL is required.")

    ydl_opts = {
        "skip_download": True,
        "quiet": True,
        "no_warnings": True,
        "extract_flat": False,
        "noplaylist": True,
        "default_search": "auto",
    }

    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=False)
    except yt_dlp.utils.YoutubeDLError as exc:
        raise MediaAnalysisError(f"Could not read media metadata: {exc}") from exc

    if not info:
        raise MediaAnalysisError("The media source returned no metadata.")

    return {
        "id": str(info.get("id") or re.sub(r"[^a-z0-9]+", "-", url.lower()).strip("-")),
        "sourceUrl": url,
        "platform": platform,
        "title": str(info.get("title") or "Untitled media"),
        "creator": str(info.get("uploader") or info.get("creator") or "Unknown creator"),
        "durationSec": int(info.get("duration") or 0),
        "thumbnailUrl": str(info.get("thumbnail") or "https://images.unsplash.com/photo-1526379095098-d400fd0bf935?auto=format&fit=crop&w=1200&q=80"),
        "uploadedAt": _format_uploaded_at(info),
        "description": info.get("description"),
        "formats": _format_formats(info),
    }


def resolve_media_preview(url: str, kind: str) -> dict[str, Any]:
    if kind not in {"audio", "video"}:
        raise ValueError("A valid media type is required.")

    ydl_opts = {
        "skip_download": True,
        "quiet": True,
        "no_warnings": True,
        "extract_flat": False,
        "noplaylist": True,
    }

    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=False)
    except yt_dlp.utils.YoutubeDLError as exc:
        raise MediaAnalysisError(f"Could not prepare media playback: {exc}") from exc

    if not info:
        raise MediaAnalysisError("The media source returned no playable stream.")

    formats = info.get("formats") or []
    candidates = []
    for entry in formats:
        stream_url = entry.get("url")
        protocol = str(entry.get("protocol") or "")
        has_video = entry.get("vcodec") not in (None, "none")
        has_audio = entry.get("acodec") not in (None, "none")
        if (
            not isinstance(stream_url, str)
            or not stream_url.startswith(("http://", "https://"))
            or protocol not in {"http", "https"}
            or (kind == "video" and not (has_video and has_audio))
            or (kind == "audio" and not has_audio)
        ):
            continue
        candidates.append(entry)

    if candidates:
        def preview_quality(entry: dict[str, Any]) -> tuple[bool | int, float]:
            if kind == "video":
                return (
                    int(entry.get("height") or 0),
                    float(entry.get("tbr") or 0),
                )
            return (
                entry.get("vcodec") in (None, "none"),
                float(entry.get("tbr") or 0),
            )

        selected = max(
            candidates,
            key=preview_quality,
        )
    else:
        if formats:
            raise MediaAnalysisError(
                "This source does not provide a progressive stream for in-app preview. "
                "Try downloading it, or use Direct Player with a direct media link."
            )
        selected = info
        stream_url = selected.get("url")
        protocol = str(selected.get("protocol") or "")
        if (
            not isinstance(stream_url, str)
            or not stream_url.startswith(("http://", "https://"))
            or protocol not in {"", "http", "https"}
            or "m3u8" in protocol.lower()
            or str(selected.get("ext") or "").lower() == "m3u8"
        ):
            raise MediaAnalysisError(
                "This source does not provide a progressive stream for in-app preview. "
                "Try downloading it, or use Direct Player with a direct media link."
            )

    stream_url = selected.get("url")
    if not isinstance(stream_url, str):
        raise MediaAnalysisError("The media source did not provide a playable stream.")

    extension = str(selected.get("ext") or "").lower()
    if extension == "m3u8" or "m3u8" in str(selected.get("protocol") or "").lower():
        raise MediaAnalysisError(
            "This source only provides an HLS playlist for preview. "
            "Use Direct Player with a direct M3U8 link instead."
        )
    parsed = urlsplit(stream_url)
    if (
        parsed.scheme not in {"http", "https"}
        or not parsed.hostname
        or parsed.username is not None
        or parsed.password is not None
    ):
        raise MediaAnalysisError("The media source returned an invalid playback URL.")

    mime_type = selected.get("mime_type")
    if isinstance(mime_type, str):
        mime_type = mime_type.split(";", 1)[0].strip()
    else:
        mime_type = mimetypes.guess_type(f"media.{extension}")[0]
    if not isinstance(mime_type, str) or not mime_type.startswith(
        "audio/" if kind == "audio" else "video/"
    ):
        if kind == "audio":
            mime_type = {
                "m4a": "audio/mp4",
                "mp4": "audio/mp4",
                "ogg": "audio/ogg",
                "opus": "audio/ogg",
                "webm": "audio/webm",
            }.get(extension, "audio/mpeg")
        else:
            mime_type = "video/mp4"

    raw_headers = selected.get("http_headers") or info.get("http_headers") or {}
    headers = (
        {
            str(name): str(value)
            for name, value in raw_headers.items()
            if isinstance(name, str) and isinstance(value, str)
        }
        if isinstance(raw_headers, dict)
        else {}
    )
    return {
        "url": stream_url,
        "headers": headers,
        "mimeType": mime_type,
    }
