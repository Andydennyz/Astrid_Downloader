from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any

import yt_dlp


class MediaAnalysisError(Exception):
    pass


def _detect_platform(url: str) -> str:
    lowered = url.lower()
    if "youtube.com" in lowered or "youtu.be" in lowered:
        return "youtube"
    if "vimeo.com" in lowered:
        return "vimeo"
    if "soundcloud.com" in lowered:
        return "soundcloud"
    if "twitch.tv" in lowered:
        return "twitch"
    if "bandcamp.com" in lowered:
        return "bandcamp"
    return "other"


def _format_formats(info: dict[str, Any]) -> list[dict[str, Any]]:
    formats: list[dict[str, Any]] = []
    for entry in info.get("formats", []) or []:
        if not entry.get("format_id"):
            continue

        format_kind = "muxed" if entry.get("vcodec") not in (None, "none") and entry.get("acodec") not in (None, "none") else "video" if entry.get("vcodec") not in (None, "none") else "audio"
        format_record = {
            "formatId": str(entry.get("format_id", "unknown")),
            "kind": format_kind,
            "container": (entry.get("ext") or "mp4").lower(),
            "height": entry.get("height"),
            "fps": entry.get("fps"),
            "videoCodec": entry.get("vcodec"),
            "audioCodec": entry.get("acodec"),
            "bitrateKbps": int(entry.get("tbr") or 0) if entry.get("tbr") is not None else None,
            "sampleRateHz": entry.get("asr"),
            "estimatedSizeBytes": entry.get("filesize") or entry.get("filesize_approx"),
            "note": entry.get("format_note"),
        }
        formats.append(format_record)

    if not formats:
        formats.append(
            {
                "formatId": "best",
                "kind": "muxed",
                "container": "mp4",
                "height": 1080,
                "note": "Fallback heuristic format generated by the backend.",
            }
        )

    return formats


def _format_uploaded_at(info: dict[str, Any]) -> str:
    timestamp = info.get("timestamp")
    if isinstance(timestamp, (int, float)) and not isinstance(timestamp, bool):
        try:
            return datetime.fromtimestamp(timestamp, timezone.utc).isoformat()
        except (OSError, OverflowError, ValueError):
            pass
    elif isinstance(timestamp, str) and timestamp.strip():
        value = timestamp.strip()
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return parsed.astimezone(timezone.utc).isoformat()
        except ValueError:
            try:
                return datetime.fromtimestamp(float(value), timezone.utc).isoformat()
            except (OSError, OverflowError, ValueError):
                pass

    upload_date = info.get("upload_date")
    if isinstance(upload_date, str):
        try:
            return datetime.strptime(upload_date, "%Y%m%d").replace(tzinfo=timezone.utc).isoformat()
        except ValueError:
            pass

    return datetime.now(timezone.utc).isoformat()


def analyze_media_url(url: str) -> dict[str, Any]:
    platform = _detect_platform(url)
    if not url:
        raise ValueError("A media URL is required.")

    ydl_opts = {
        "skip_download": True,
        "quiet": True,
        "no_warnings": True,
        "extract_flat": False,
        "noplaylist": True,
        "default_search": "auto",
    }

    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=False)
    except yt_dlp.utils.YoutubeDLError as exc:
        raise MediaAnalysisError(f"Could not read media metadata: {exc}") from exc

    if not info:
        raise MediaAnalysisError("The media source returned no metadata.")

    return {
        "id": str(info.get("id") or re.sub(r"[^a-z0-9]+", "-", url.lower()).strip("-")),
        "sourceUrl": url,
        "platform": platform,
        "title": str(info.get("title") or "Untitled media"),
        "creator": str(info.get("uploader") or info.get("creator") or "Unknown creator"),
        "durationSec": int(info.get("duration") or 0),
        "thumbnailUrl": str(info.get("thumbnail") or "https://images.unsplash.com/photo-1526379095098-d400fd0bf935?auto=format&fit=crop&w=1200&q=80"),
        "uploadedAt": _format_uploaded_at(info),
        "description": info.get("description"),
        "formats": _format_formats(info),
    }
